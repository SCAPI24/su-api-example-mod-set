  /* ------------------------------------------------------------------ 语言状态 */

  var language = DEFAULT_LANGUAGE;

  function normalize(lang) {
    return String(lang || '').toLowerCase().indexOf('en') === 0 ? 'en' : 'zh';
  }

  function detect() {
    try {
      var saved = global.localStorage.getItem(STORAGE_KEY);
      if (saved) return normalize(saved);
    } catch (error) { /* 隐私模式 */ }
    var query = /[?&]lang=(zh|en)\b/i.exec(global.location ? global.location.search : '');
    if (query) return normalize(query[1]);
    return DEFAULT_LANGUAGE;
  }

  function setLanguage(lang) {
    language = normalize(lang);
    try {
      global.localStorage.setItem(STORAGE_KEY, language);
    } catch (error) { /* 隐私模式：只影响"下次打开" */ }
    return language;
  }

  function getLanguage() {
    return language;
  }

  /** 取一条文案：当前语言 → 中文兜底 → key 本身（永不返回 undefined）。 */
  function t(key, fallback) {
    var table = STRINGS[language] || {};
    if (table[key] !== undefined) return table[key];
    var zh = STRINGS.zh || {};
    if (zh[key] !== undefined) return zh[key];
    return fallback !== undefined ? fallback : key;
  }

  /**
   * 带占位符的整句文案：`format('st.c001', '已保存 {0}', file)`。
   *
   * 为什么要有它：状态提示里有一批是**拼接**出来的（`'已保存 ' + file + '（' + n + ' 节点）'`）。
   * 碎片单独翻译是错的（`' 个节点'` 离开原句没有意义），而且中英文语序不同
   * （"已保存 X（N 节点）" vs "Saved X (N nodes)"）—— 所以把整句做成模板，只替换值。
   * 缺失的参数原样留 `{n}`：宁可露出占位符，也不要悄悄吞掉信息。
   */
  function format(key, fallback) {
    var text = t(key, fallback);
    var values = Array.prototype.slice.call(arguments, 2);
    if (!values.length) return text;
    return String(text).replace(/\{(\d+)\}/g, function (match, index) {
      var i = parseInt(index, 10);
      return i >= 0 && i < values.length ? String(values[i]) : match;
    });
  }

  /** 节点的**显示名**（只有显示用；包里始终是 `type` 原文）。 */
  function nodeLabel(type) {
    var entry = NODE_LABELS[type];
    if (entry && entry[language]) return entry[language];
    return type;
  }

  /** 节点显示时附带的"原始类型"（英文下与显示名相同就返回空串，不重复显示）。 */
  function nodeRawHint(type) {
    var label = nodeLabel(type);
    return label === type ? '' : type;
  }

  /** 有没有这条翻译（自检用）。 */
  function hasNodeLabel(type) {
    return !!NODE_LABELS[type];
  }

  /**
   * 搜索用的"全名"：**类型标识 + 中文名 + 英文名**。
   *
   * 为什么三种都要：物料区搜索以前只匹配类型标识（`app.js` 里拼的 haystack），
   * 于是中文界面下搜「冷却」「循环」「等待」全是空结果 —— 用户记不住 `Cooldown` 这种标识。
   * 反过来英文界面下也可能想搜中文名（对着文档找），所以两边都塞进去，成本只有几十字节。
   */
  function nodeLabelSearch(type) {
    var entry = NODE_LABELS[type];
    if (!entry)
      return String(type === undefined || type === null ? '' : type);
    return [type, entry.zh, entry.en].filter(function (part) { return !!part; }).join(' ');
  }

  /** 中文里用到 `·` 分隔（任务·日志），英文用空格 —— 只是显示风格，与包无关。 */
  function splitNodeLabel(type) {
    return nodeLabel(type).split(/·/);
  }

